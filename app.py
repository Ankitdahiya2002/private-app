@socketio.on("join")
def on_join(data):
    """Client joins a room. data = {username, room}"""
    username = (data.get("username") or "").strip()
    room = (data.get("room") or "").strip().upper()
    if not username or not room:
        return

    join_room(room)

    # Track online
    if room not in online:
        online[room] = {}
    online[room][request.sid] = username

    # Track user in Supabase
    try:
        storage.upsert_user(username, room, True)
    except Exception as e:
        print(f"Failed to upsert user: {e}")

    # Send message history to this client only
    history = storage.get_messages(room)
    emit("history", history)

    # Notify others that user came online
    emit(
        "user_joined",
        {"username": username, "online_users": list(online[room].values())},
        to=room,
        include_self=False,
    )

    # Send online list to the joining user
    emit("online_users", list(online[room].values()))


@socketio.on("disconnect")
def on_disconnect():
    sid = request.sid
    # Find which room this sid belongs to
    for room, users in list(online.items()):
        if sid in users:
            username = users.pop(sid)
            
            # Update user in Supabase to offline
            try:
                storage.upsert_user(username, room, False)
            except Exception as e:
                print(f"Failed to upsert user: {e}")
                
            emit(
                "user_left",
                {"username": username, "online_users": list(users.values())},
                to=room,
            )
            break


@socketio.on("message")
def on_message(data):
    """
    data = {
        room: str,
        sender: str,
        text: str | None,
        image_url: str | None,
        id: str,       # UUID generated by client
        ts: float,     # Unix timestamp (ms) from client
    }
    """
    room = (data.get("room") or "").strip().upper()
    if not room:
        return

    msg = {
        "id": data.get("id", uuid.uuid4().hex),
        "room": room,
        "sender": data.get("sender", ""),
        "text": data.get("text", ""),
        "image_url": data.get("image_url", ""),
        "ts": data.get("ts", time.time() * 1000),
        "seen": False,
    }

    storage.add_message(room, msg)
    emit("message", msg, to=room)


@socketio.on("typing")
def on_typing(data):
    room = (data.get("room") or "").strip().upper()
    emit("typing", {"username": data.get("username")}, to=room, include_self=False)


@socketio.on("stop_typing")
def on_stop_typing(data):
    room = (data.get("room") or "").strip().upper()
    emit("stop_typing", {"username": data.get("username")}, to=room, include_self=False)


@socketio.on("seen")
def on_seen(data):
    """data = {room, reader, up_to_ts}"""
    room = (data.get("room") or "").strip().upper()
    reader = data.get("reader", "")
    up_to_ts = data.get("up_to_ts", 0)
    storage.mark_seen(room, up_to_ts, reader)
    emit("seen", {"reader": reader, "up_to_ts": up_to_ts}, to=room, include_self=False)


@socketio.on("delete_message")
def on_delete(data):
    """data = {room, msg_id, delete_for: 'me'|'everyone'}"""
    room = (data.get("room") or "").strip().upper()
    msg_id = data.get("msg_id", "")
    delete_for = data.get("delete_for", "me")

    if delete_for == "everyone":
        deleted = storage.delete_message(room, msg_id)
        if deleted:
            emit("delete_message", {"msg_id": msg_id}, to=room)
    else:
        # Just emit back to sender only
        emit("delete_message", {"msg_id": msg_id})


